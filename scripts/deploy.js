const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  const [deployer] = await hre.ethers.getSigners();

  console.log("==================================================");
  console.log("TrustLedger - Blockchain Deployment");
  console.log("==================================================");
  console.log("Deploying contracts with account:", deployer.address);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log("Account balance:", hre.ethers.formatEther(balance), "ETH");

  const CharityPlatform = await hre.ethers.getContractFactory("CharityPlatform");
  const charityPlatform = await CharityPlatform.deploy();

  await charityPlatform.waitForDeployment();
  const contractAddress = await charityPlatform.getAddress();

  console.log("--------------------------------------------------");
  console.log("CharityPlatform deployed to:", contractAddress);
  console.log("Platform Administrator (Admin):", deployer.address);
  console.log("--------------------------------------------------");

  // Extract ABI from Hardhat artifacts
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/CharityPlatform.sol/CharityPlatform.json"
  );
  const contractArtifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  // Ensure frontend config directory exists
  const frontendConfigDir = path.join(__dirname, "../frontend/src/config");
  if (!fs.existsSync(frontendConfigDir)) {
    fs.mkdirSync(frontendConfigDir, { recursive: true });
  }

  // Write contract configuration for frontend
  const configContent = `// Auto-generated by scripts/deploy.js on ${new Date().toISOString()}
// Do NOT modify manually unless changing deployment target

export const CONTRACT_ADDRESS = "${contractAddress}";
export const PLATFORM_ADMIN_ADDRESS = "${deployer.address}";
export const NETWORK_CHAIN_ID = 31337;
export const RPC_URL = "http://127.0.0.1:8545";

export const CONTRACT_ABI = ${JSON.stringify(contractArtifact.abi, null, 2)};
`;

  const configPath = path.join(frontendConfigDir, "contractConfig.js");
  fs.writeFileSync(configPath, configContent, "utf8");
  console.log("Contract configuration saved to:", configPath);

  // Seed sample initial campaigns for an immediate rich local demonstration if desired
  const network = hre.network.name;
  if (network === "localhost" || network === "hardhat") {
    console.log("Seeding sample demonstration campaigns on local network...");
    const currentTime = Math.floor(Date.now() / 1000);
    const sevenDays = 7 * 24 * 60 * 60;
    const fourteenDays = 14 * 24 * 60 * 60;

    // Campaign 1: Clean Water Initiative (will be verified)
    const tx1 = await charityPlatform.createCampaign(
      "Rural Clean Water & Sanitation Project",
      "Building solar-powered water purification wells and sanitary infrastructure for vulnerable rural villages.",
      hre.ethers.parseEther("5.0"),
      currentTime + sevenDays
    );
    await tx1.wait();

    // Verify Campaign 1
    const verifyTx = await charityPlatform.verifyCampaign(1);
    await verifyTx.wait();

    // Campaign 2: Pediatric Emergency Healthcare
    const tx2 = await charityPlatform.createCampaign(
      "Pediatric Emergency Healthcare & Supplies",
      "Funding critical neonatal incubators, diagnostic medicines, and emergency treatments for underprivileged children's hospitals.",
      hre.ethers.parseEther("3.5"),
      currentTime + fourteenDays
    );
    await tx2.wait();
    const verifyTx2 = await charityPlatform.verifyCampaign(2);
    await verifyTx2.wait();

    // Campaign 3: Community Library & Digital Lab (Pending verification)
    const tx3 = await charityPlatform.createCampaign(
      "Community Digital Learning Center",
      "Equipping youth community centers with computers, open-source educational software, and STEM books.",
      hre.ethers.parseEther("2.0"),
      currentTime + sevenDays
    );
    await tx3.wait();

    console.log("Seeded 3 realistic demonstration campaigns (2 verified, 1 pending verification).");
  }

  console.log("==================================================");
  console.log("Deployment and setup complete!");
  console.log("==================================================");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });
